function drukDoc(titel, body) {
  const f = document.createElement('iframe');
  f.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0';
  document.body.append(f);
  const d = f.contentDocument;
  d.open(); d.write(`<!doctype html><html lang="nl"><head><meta charset="utf-8"><title>${escHTML(titel)}</title><style>${DRUK_CSS}</style></head><body>${body}</body></html>`); d.close();
  setTimeout(() => { try { f.contentWindow.focus(); f.contentWindow.print(); } finally { setTimeout(() => f.remove(), 60000); } }, 300);
}
