function leesSolo(tekst) {
  const blokken = String(tekst || '').replace(/\r/g, '').split(/\n\s*\n/).map(b => b.split('\n').map(r => r.trim()).filter(Boolean)).filter(b => b.length);
  const uit = [];
  for (const b of blokken) {
    let regels = b.flatMap(r => r.length > 140 ? splitsZinnen(r) : [r]);
    if (regels.length > 8 && b.length === 1) { for (let i = 0; i < regels.length; i += 3) uit.push(regels.slice(i, i + 3)); }
    else uit.push(regels);
  }
  return uit;
}
