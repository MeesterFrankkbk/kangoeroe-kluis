function leesToneel(tekst) {
  return String(tekst || '').split(/\r?\n/).map(l => l.trim()).filter(Boolean).map(l => {
    if (l.startsWith('(') && l.endsWith(')')) return { regie: l.slice(1, -1) };
    const m = l.match(/^([^:()]{1,40}):\s*(.+)$/);
    if (!m) return { regie: l };
    const rol = m[1].trim(), tekst = m[2].replace(/\([^)]*\)/g, ' ').replace(/\s+/g, ' ').trim();
    return { rol, rollen: rol.split(/\s*(?:&|,| en )\s*/), vol: m[2], tekst };
  });
}
const woordenVan = s => U.normZin(s, false).split(' ').filter(Boolean);
function gelijkenis(a, b) {
  const x = woordenVan(a), y = woordenVan(b);
  if (!y.length) return 1;
  const L = Array.from({ length: x.length + 1 }, () => Array(y.length + 1).fill(0));
  for (let i = 1; i <= x.length; i++) for (let j = 1; j <= y.length; j++) L[i][j] = x[i - 1] === y[j - 1] ? L[i - 1][j - 1] + 1 : Math.max(L[i - 1][j], L[i][j - 1]);
  return L[x.length][y.length] / Math.max(x.length, y.length);
}
